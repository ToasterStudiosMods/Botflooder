BOT_RUNNER_JS = r'''/* Auto-generated by app.py. Mineflayer offline-mode bot runner. */
const mineflayer = require('mineflayer');

const args = process.argv.slice(2);
// args: name host port version behavior reconnect
const config = {
  name: args[0] || 'Bot',
  host: args[1] || 'localhost',
  port: parseInt(args[2] || '25565', 10),
  version: (args[3] && args[3] !== 'auto') ? args[3] : null,
  behavior: args[4] || 'idle',
  reconnect: String(args[5] || 'true') === 'true',
};

let bot = null;
let behaviorTimer = null;
let reconnectTimer = null;
let shouldRun = true;

function emit(obj) {
  try { process.stdout.write(JSON.stringify(obj) + '\n'); } catch (e) {}
}
function log(msg) { emit({ type: 'log', message: String(msg), time: Date.now() }); }
function setStatus(s) { emit({ type: 'status', status: s, time: Date.now() }); }

function startBehavior(b) {
  if (behaviorTimer) { clearInterval(behaviorTimer); behaviorTimer = null; }
  try {
    switch (config.behavior) {
      case 'idle':
        behaviorTimer = setInterval(() => {
          try { b.look(Math.random() * Math.PI * 2, (Math.random() - 0.5) * 0.6); } catch (e) {}
        }, 4000 + Math.random() * 4000);
        break;
      case 'wander':
        behaviorTimer = setInterval(() => {
          try {
            const r = Math.random();
            if (r < 0.25) {
              b.setControlState('jump', true);
              setTimeout(() => { try { b.setControlState('jump', false); } catch (e) {} }, 400);
            } else {
              b.look(Math.random() * Math.PI * 2, 0);
              b.setControlState('forward', true);
              setTimeout(() => { try { b.setControlState('forward', false); } catch (e) {} }, 1000 + Math.random() * 2500);
            }
          } catch (e) {}
        }, 2400);
        break;
      case 'jump':
        behaviorTimer = setInterval(() => {
          try { b.setControlState('jump', true); setTimeout(() => { try { b.setControlState('jump', false); } catch (e) {} }, 300); } catch (e) {}
        }, 1400 + Math.random() * 1400);
        break;
      case 'spin':
        let yaw = 0;
        behaviorTimer = setInterval(() => {
          try { yaw += 0.45; b.look(yaw % (Math.PI * 2), 0); } catch (e) {}
        }, 90);
        break;
      case 'sneak':
        behaviorTimer = setInterval(() => {
          try {
            const sneak = Math.random() > 0.5;
            b.setControlState('sneak', sneak);
          } catch (e) {}
        }, 3000);
        break;
      case 'follow':
        behaviorTimer = setInterval(() => {
          try {
            const players = Object.values(b.players || {}).filter(p => p && p.entity && p.username !== b.username);
            if (players.length) {
              const target = players[0].entity.position;
              b.lookAt(target.offset(0, 1.6, 0));
              const dist = b.entity.position.distanceTo(target);
              b.setControlState('forward', dist > 2.5);
              b.setControlState('sprint', dist > 8);
            } else {
              b.setControlState('forward', false);
              b.setControlState('sprint', false);
            }
          } catch (e) {}
        }, 500);
        break;
      case 'chat':
        const msgs = ['hi', 'lol', 'gg', 'anyone here?', 'nice', 'brb', 'hello!', 'wow', 'cool', 'yo'];
        behaviorTimer = setInterval(() => {
          try { b.chat(msgs[Math.floor(Math.random() * msgs.length)]); } catch (e) {}
        }, 9000 + Math.random() * 7000);
        break;
      case 'punch':
        behaviorTimer = setInterval(() => {
          try {
            const target = b.nearestEntity(e => e && e.position && e.position.distanceTo(b.entity.position) < 4);
            if (target) {
              b.lookAt(target.position.offset(0, 1, 0));
              b.attack(target);
            }
          } catch (e) {}
        }, 2000);
        break;
      default: // idle
        behaviorTimer = setInterval(() => {
          try { b.look(Math.random() * Math.PI * 2, 0); } catch (e) {}
        }, 5000);
    }
  } catch (e) {
    log('behavior error: ' + (e && e.message));
  }
}

function createBot() {
  if (!shouldRun) return;
  setStatus('connecting');
  log('Connecting to ' + config.host + ':' + config.port + ' as "' + config.name + '"' + (config.version ? ' (v' + config.version + ')' : ' (auto version)'));

  const opts = {
    username: config.name,
    host: config.host,
    port: config.port,
    auth: 'offline',
    hideErrors: false,
  };
  if (config.version) opts.version = config.version;

  try {
    bot = mineflayer.createBot(opts);
  } catch (e) {
    log('createBot error: ' + (e && e.message));
    setStatus('error');
    if (shouldRun && config.reconnect) {
      reconnectTimer = setTimeout(createBot, 6000);
    }
    return;
  }

  bot.on('spawn', () => {
    setStatus('online');
    try {
      const p = bot.entity.position;
      log('Spawned at ' + p.x.toFixed(1) + ', ' + p.y.toFixed(1) + ', ' + p.z.toFixed(1) + ' (health ' + (bot.health != null ? bot.health.toFixed(0) : '?') + ')');
    } catch (e) { log('Spawned.'); }
    startBehavior(bot);
  });

  bot.on('health', () => {
    try { emit({ type: 'health', health: bot.health, food: bot.food, time: Date.now() }); } catch (e) {}
  });

  bot.on('chat', (username, message) => {
    if (username === config.name) return;
    log('[chat] ' + username + ': ' + message);
  });

  bot.on('kicked', (reason) => {
    let r = reason;
    try { if (typeof reason === 'object') r = JSON.stringify(reason); } catch (e) {}
    log('Kicked: ' + r);
    setStatus('offline');
  });

  bot.on('error', (err) => {
    log('Error: ' + (err && err.message ? err.message : err));
    setStatus('error');
  });

  bot.on('end', () => {
    if (behaviorTimer) { clearInterval(behaviorTimer); behaviorTimer = null; }
    setStatus('offline');
    log('Disconnected.');
    if (shouldRun && config.reconnect) {
      log('Reconnecting in 6s ...');
      reconnectTimer = setTimeout(createBot, 6000);
    }
  });
}

createBot();

function shutdown() {
  shouldRun = false;
  if (reconnectTimer) clearTimeout(reconnectTimer);
  if (behaviorTimer) clearInterval(behaviorTimer);
  try { bot && bot.quit('Bye'); } catch (e) {}
  setTimeout(() => process.exit(0), 400);
}
process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);
'''


