@app.route("/api/stop_all", methods=["POST"])
def api_stop_all():
    with bots_lock:
        ids = [bid for bid, b in bots.items() if b["status"] not in ("stopped", "offline", "error")]
    n = 0
    for bid in ids:
        if stop_bot(bid):
            n += 1
    push_log(None, "system", "Stopping %d active bot(s) ..." % n, "system")
    return jsonify({"stopping": n})


@app.route("/api/clear", methods=["POST"])
def api_clear():
    """Remove stopped/offline/error bots from the list."""
    with bots_lock:
        keep = {}
        removed = 0
        for bid, b in bots.items():
            if b["status"] in ("stopped", "offline", "error"):
                removed += 1
            else:
                keep[bid] = b
        bots.clear()
        bots.update(keep)
    return jsonify({"removed": removed})


@app.route("/api/logs")
def api_logs():
    """Server-Sent Events stream of live logs."""
    q = queue.Queue()
    with sub_lock:
        log_subscribers.append(q)

    def stream():
        # send recent history first
        yield "retry: 3000\n\n"
        for entry in list(log_buffer):
            yield "data: " + json.dumps(entry) + "\n\n"
        try:
            while True:
                try:
                    msg = q.get(timeout=20)
                    yield "data: " + json.dumps(msg) + "\n\n"
                except queue.Empty:
                    yield ": keepalive\n\n"
        finally:
            with sub_lock:
                if q in log_subscribers:
                    log_subscribers.remove(q)

    return Response(stream(), mimetype="text/event-stream", headers={
        "Cache-Control": "no-cache",
        "X-Accel-Buffering": "no",
        "Connection": "keep-alive",
    })


