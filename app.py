def ensure_environment():
    """Check Node/npm, write bot_runner.js, install mineflayer if missing."""
    global READY, INSTALL_ERROR

    RUNTIME_DIR.mkdir(parents=True, exist_ok=True)

    if not NODE_BIN:
        INSTALL_ERROR = ("Node.js was not found on your PATH. "
                         "Install Node.js 16+ from https://nodejs.org and restart.")
        print("[setup] ERROR: " + INSTALL_ERROR)
        return

    # Always (re)write the runner so it stays in sync with this app version.
    try:
        BOT_RUNNER_PATH.write_text(BOT_RUNNER_JS, encoding="utf-8")
    except Exception as e:
        INSTALL_ERROR = "Could not write bot_runner.js: " + str(e)
        print("[setup] ERROR: " + INSTALL_ERROR)
        return

    # Write a LOCAL package.json so npm installs into ./runtime/node_modules
    # instead of walking up and polluting a parent project.
    pkg_json = {
        "name": "mc-summoner-runtime",
        "version": "1.0.0",
        "private": True,
        "description": "Runtime deps for MC Bot Summoner bots (mineflayer).",
        "dependencies": {"mineflayer": "^4.20.1"},
    }
    try:
        (RUNTIME_DIR / "package.json").write_text(
            json.dumps(pkg_json, indent=2), encoding="utf-8")
    except Exception as e:
        INSTALL_ERROR = "Could not write package.json: " + str(e)
        print("[setup] ERROR: " + INSTALL_ERROR)
        return

    nm_mineflayer = RUNTIME_DIR / "node_modules" / "mineflayer"
    if not nm_mineflayer.exists():
        print("[setup] Installing mineflayer (one-time, ~30s) ...")
        try:
            subprocess.run(
                [NPM_BIN or "npm", "install",
                 "--no-audit", "--no-fund", "--loglevel=error"],
                cwd=str(RUNTIME_DIR),
                check=True,
                timeout=240,
            )
            print("[setup] mineflayer installed.")
        except subprocess.CalledProcessError as e:
            INSTALL_ERROR = ("npm install mineflayer failed (exit code %s). "
                             "Check your internet connection and npm setup."
                             % getattr(e, "returncode", "?"))
            print("[setup] ERROR: " + INSTALL_ERROR)
            return
        except subprocess.TimeoutExpired:
            INSTALL_ERROR = "npm install mineflayer timed out. Check your connection."
            print("[setup] ERROR: " + INSTALL_ERROR)
            return

    READY = True
    print("[setup] Ready. Node: %s | mineflayer present." % NODE_BIN)


