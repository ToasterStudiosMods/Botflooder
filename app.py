@app.route("/api/state")
def api_state():
    with bots_lock:
        blist = [public_bot(b) for b in bots.values()]
    counts = {"total": len(blist), "online": 0, "connecting": 0,
              "queued": 0, "offline": 0, "error": 0, "stopped": 0}
    for b in blist:
        s = b["status"]
        if s in counts:
            counts[s] += 1
        else:
            counts["offline"] += 1
    queued_pending = spawn_queue.qsize()
    return jsonify({
        "ready": READY,
        "install_error": INSTALL_ERROR,
        "node": NODE_BIN,
        "spawn_queue": queued_pending,
        "counts": counts,
        "bots": blist,
    })


@app.route("/api/spawn", methods=["POST"])
def api_spawn():
    if not READY:
        return jsonify({"error": INSTALL_ERROR or "Runtime not ready."}), 503
    data = request.get_json(silent=True) or {}

    host = (data.get("host") or "").strip()
    if not host:
        return jsonify({"error": "Server host/IP is required."}), 400
    try:
        port = int(data.get("port") or 25565)
    except ValueError:
        return jsonify({"error": "Port must be a number."}), 400
    if not (1 <= port <= 65535):
        return jsonify({"error": "Port must be between 1 and 65535."}), 400

    version = (data.get("version") or "auto").strip()
    behavior = (data.get("behavior") or "idle").strip()
    reconnect = bool(data.get("reconnect", True))
    name_mode = (data.get("name_mode") or "prefix").strip()
    prefix = (data.get("prefix") or "Bot").strip()
    try:
        count = int(data.get("count") or 1)
    except ValueError:
        return jsonify({"error": "Count must be a number."}), 400
    if count < 1:
        return jsonify({"error": "Count must be at least 1."}), 400
    if count > 100000:
        return jsonify({"error": "Count capped at 100000 for sanity. Each bot is a Node process (~40MB RAM)."}), 400

    with bots_lock:
        existing = [b["name"] for b in bots.values()]
    names = generate_names(name_mode, prefix, count, existing)

    ids = []
    for nm in names:
        bid = queue_bot(nm, host, port, version, behavior, reconnect)
        ids.append({"id": bid, "name": nm})

    push_log(None, "system",
             "Queued %d bot(s) -> %s:%s (%s)" % (len(names), host, port, behavior), "system")
    return jsonify({"queued": len(names), "bots": ids})


