#!/usr/bin/env python3
"""
MC Bot Summoner
===============
A self-contained Flask web app that summons any number of FAKE Minecraft
players (offline-mode / "cracked" bots) to a target server.

Inspired by the mindcraft project (https://github.com/mindcraft-bots/mindcraft)
which uses the Node.js `mineflayer` library. This app wraps that approach in a
friendly web UI and orchestrates many bot processes from Python.

On first run it automatically:
  * checks that Node.js + npm are installed
  * writes a `bot_runner.js` Mineflayer script into ./runtime
  * runs `npm install mineflayer` into ./runtime/node_modules

Then it starts a Flask server on http://0.0.0.0:3000.

Usage:
    python3 app.py

Requirements:
    - Python 3.8+  (Flask is pip-installed automatically if missing)
    - Node.js 16+  (must be installed already)
    - npm          (ships with Node.js)

The target server MUST be running in offline mode (server.properties:
`online-mode=false`) for offline players to join.
"""

