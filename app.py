def push_log(bot_id, name, message, kind="log"):
    entry = {
        "bot_id": bot_id,
        "name": name,
        "message": message,
        "kind": kind,  # log | status | error | system
        "time": int(time.time() * 1000),
    }
    log_buffer.append(entry)
    with sub_lock:
        dead = []
        for q in log_subscribers:
            try:
                q.put_nowait(entry)
            except Exception:
                dead.append(q)
        if dead:
            for q in dead:
                try:
                    log_subscribers.remove(q)
                except ValueError:
                    pass


def queue_bot(name, host, port, version, behavior, reconnect):
    bot_id = uuid.uuid4().hex[:10]
    info = {
        "id": bot_id,
        "name": name,
        "host": host,
        "port": port,
        "version": version,
        "behavior": behavior,
        "reconnect": reconnect,
        "status": "queued",
        "started_at": time.time(),
        "pid": None,
        "position": None,
        "health": None,
    }
    with bots_lock:
        bots[bot_id] = info
    spawn_queue.put({"bot_id": bot_id, "name": name, "host": host, "port": port,
                     "version": version, "behavior": behavior, "reconnect": reconnect})
    return bot_id


def do_spawn(job):
    bot_id = job["bot_id"]
    with bots_lock:
        info = bots.get(bot_id)
        if not info:
            return
        info["status"] = "connecting"
    cmd = [
        NODE_BIN,
        str(BOT_RUNNER_PATH),
        job["name"],
        job["host"],
        str(job["port"]),
        job["version"],
        job["behavior"],
        "true" if job["reconnect"] else "false",
    ]
    try:
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            cwd=str(RUNTIME_DIR),
            text=True,
            bufsize=1,
            env=dict(os.environ, DEBUG=""),
        )
    except Exception as e:
        with bots_lock:
            if bot_id in bots:
                bots[bot_id]["status"] = "error"
        push_log(bot_id, job["name"], "Failed to launch: " + str(e), "error")
        return

    with bots_lock:
        if bot_id in bots:
            bots[bot_id]["pid"] = proc.pid
            bots[bot_id]["proc"] = proc
    threading.Thread(target=reader_thread, args=(bot_id, proc), daemon=True).start()


def spawn_worker():
    while True:
        job = spawn_queue.get()
        try:
            do_spawn(job)
        except Exception as e:
            print("[worker] spawn error:", e)
        time.sleep(SPAWN_DELAY)
        spawn_queue.task_done()


def reader_thread(bot_id, proc):
    name = ""
    with bots_lock:
        name = bots.get(bot_id, {}).get("name", "")
    try:
        for line in proc.stdout:
            line = line.rstrip("\n")
            if not line.strip():
                continue
            try:
                obj = json.loads(line)
            except ValueError:
                push_log(bot_id, name, line, "log")
                continue
            t = obj.get("type")
            if t == "status":
                with bots_lock:
                    if bot_id in bots:
                        bots[bot_id]["status"] = obj.get("status", "offline")
                push_log(bot_id, name, "status -> " + obj.get("status", ""), "status")
            elif t == "log":
                push_log(bot_id, name, obj.get("message", ""), "log")
            elif t == "health":
                with bots_lock:
                    if bot_id in bots:
                        bots[bot_id]["health"] = obj.get("health")
            else:
                push_log(bot_id, name, json.dumps(obj), "log")
    except Exception as e:
        push_log(bot_id, name, "reader error: " + str(e), "error")
    finally:
        proc.wait()
        with bots_lock:
            if bot_id in bots:
                cur = bots[bot_id]["status"]
                if cur not in ("stopped", "error"):
                    bots[bot_id]["status"] = "offline"
        push_log(bot_id, name, "process exited (code %s)" % proc.returncode, "system")


def stop_bot(bot_id):
    with bots_lock:
        info = bots.get(bot_id)
        if not info:
            return False
        proc = info.get("proc")
        info["status"] = "stopped"
    if proc and proc.poll() is None:
        try:
            proc.terminate()
        except Exception:
            pass
        # hard kill after grace
        threading.Thread(target=lambda: (time.sleep(3),
                                         proc.poll() is None and (proc.kill() if proc.poll() is None else None)),
                         daemon=True).start()
    push_log(bot_id, info.get("name", ""), "Stopped by user.", "system")
    return True


