NAME_ADJ = ["Cool", "Fast", "Brave", "Sly", "Mega", "Super", "Dark", "Epic",
            "Lucky", "Quick", "Iron", "Gold", "Red", "Cyber", "Neon", "Hyper",
            "Silent", "Wild", "Mighty", "Proto"]
NAME_NOUN = ["Steve", "Alex", "Creeper", "Zombie", "Miner", "Builder", "Knight",
             "Wizard", "Ninja", "Pirate", "Hunter", "Wolf", "Tiger", "Dragon",
             "Phoenix", "Gamer", "Pro", "Noob", "King", "Queen"]

NAME_RE = re.compile(r"^[A-Za-z0-9_]{3,16}$")


def sanitize_name(name):
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    name = name[:16]
    if len(name) < 3:
        name = (name + "Bot")[:16]
    return name


def generate_names(mode, prefix, count, existing):
    names = []
    used = set(existing)
    prefix = sanitize_name(prefix) if prefix else "Bot"

    def take(n):
        n = sanitize_name(n)
        base = n
        i = 1
        while n in used:
            suffix = "_" + str(i)
            n = (base[:16 - len(suffix)] + suffix)
            i += 1
        used.add(n)
        return n

    if mode == "prefix":
        for i in range(1, count + 1):
            s = str(i)
            base = prefix[:16 - len(s) - 1]
            names.append(take(base + "_" + s))
    elif mode == "steve":
        for i in range(count):
            names.append(take("Steve" + (str(i + 1) if i > 0 else "")))
    elif mode == "random":
        for _ in range(count):
            n = random.choice(NAME_ADJ) + random.choice(NAME_NOUN) + str(random.randint(1, 99))
            names.append(take(n[:16]))
    else:
        for i in range(count):
            names.append(take(prefix + "_" + str(i + 1)))
    return names


